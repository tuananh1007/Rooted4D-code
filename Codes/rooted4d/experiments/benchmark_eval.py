r"""Evaluate the framework on the semi-synthetic benchmark built from real donors.

This is the arm the procedural experiments cannot supply. Experiment E5 runs the
baseline ladder on geometry generated by the same low-dimensional model that then
fits it, which is an inverse crime: the truth is exactly representable, so the
residual measures the optimizer rather than the method. Here the geometry comes
from real ACDC chambers and real MVSeg2023 valves, the observations come from a
free per-vertex Fourier motion field, and the solver sees only a rank-limited
latent model learned from *other people*. Nothing about the test donors is
representable by construction.

Two consequences follow, and both are reported rather than hidden:

* The learned basis cannot span unseen anatomy exactly, so there is a
  representation floor below which no arm can go. It is measured directly
  (:func:`representation_error`) and printed beside the fitted errors, because
  a held-out error that merely matches the floor demonstrates nothing about
  inference.
* Identity and motion truth do not exist in the solver's latent space. Only
  pose, phase and the held-out point evidence are scored against stored truth.
"""

from __future__ import annotations

import json
from dataclasses import replace
from pathlib import Path
from typing import Any

import numpy as np

from rooted4d.inference.baselines import BASELINE_IDS, _matrix_to_axis_angle, run_all_arms
from rooted4d.inference.joint import session_rows, Observations, SolverConfig
from rooted4d.inference.problem import JointProblem
from rooted4d.inference.scene import SceneModel, SceneParameters
from rooted4d.priors.gauges import GaugedLatentBases

BENCHMARK_ROOT = Path("data/derived/semisynthetic-real-v1")

#: Fields every sample must carry for the loader to trust it.
_REQUIRED = (
    "template_vertices",
    "motion_coefficients",
    "session_static",
    "session_dynamic",
    "cmr_times",
    "cmr_indices",
    "cmr_points",
    "tee_times",
    "tee_indices",
    "tee_points",
    "pose_rotation",
    "pose_translation",
    "phase_offset",
    "phase_logits",
)


def sample_paths(root: Path, split: str) -> list[Path]:
    paths = sorted((Path(root) / "samples" / split).glob("*.npz"))
    if not paths:
        raise FileNotFoundError(f"no samples for split {split!r} under {root}")
    return paths


def _load(path: Path) -> dict[str, Any]:
    with np.load(path, allow_pickle=True) as handle:
        missing = [name for name in _REQUIRED if name not in handle.files]
        if missing:
            raise KeyError(f"{path.name} is missing {missing}")
        return {name: handle[name] for name in handle.files}


def benchmark_topology(root: Path | str, split: str = "train") -> dict[str, int]:
    """The procedural topology a benchmark was generated on, from its first sample (W2.6)."""

    from rooted4d.geometry import sample_topology

    with np.load(sample_paths(Path(root), split)[0], allow_pickle=True) as handle:
        return sample_topology(handle)


def _identity_geometry(
    root: Path, split: str, exclude: frozenset[str] | set[str] | None = None
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """One row per *identity*, not per sample.

    ``exclude`` drops identities entirely, which is how a cross-validation fold
    learns its bases without the identities it will be scored on.

    Variants of an identity share donor geometry, so counting them separately
    would let a 90-identity training set masquerade as 180 independent shapes
    and would silently overweight whichever identities happen to have more
    variants.
    """

    templates: dict[str, np.ndarray] = {}
    motions: dict[str, np.ndarray] = {}
    sessions: dict[str, np.ndarray] = {}
    for path in sample_paths(root, split):
        data = _load(path)
        key = str(data["identity_id"])
        if exclude and key in exclude:
            continue
        templates.setdefault(key, data["template_vertices"])
        motions.setdefault(key, data["motion_coefficients"])
        sessions.setdefault(
            key, np.stack([data["session_static"], data["session_dynamic"]], axis=0)
        )
    order = sorted(templates)
    return (
        np.stack([templates[k] for k in order]),
        np.stack([motions[k] for k in order]),
        np.stack([sessions[k] for k in order]),
    )


def fit_benchmark_model(
    root: Path | str = BENCHMARK_ROOT,
    *,
    n_modes: int = 12,
    n_motion: int = 4,
    n_session: int = 2,
    n_phase_nodes: int = 8,
    exclude_identities: frozenset[str] | set[str] | None = None,
) -> tuple[SceneModel, dict[str, Any]]:
    """Learn the shape space from the *train* split only, then freeze it.

    The topology is the shared procedural complex, so the attachment map and the
    visibility groups are the same object every sample was generated against.
    What is learned here is the reduced shape space and the motion/session
    subspace split, and it is learned from 90 training identities that share no
    donor and no source person with validation or test.
    """

    root = Path(root)
    templates, motions, sessions = _identity_geometry(root, "train", exclude_identities)
    n_vertices = templates.shape[1]

    mean_template = templates.mean(axis=0)
    deviations = (templates - mean_template).reshape(len(templates), -1)
    # A basis of rank n_modes needs at least n_modes independent donors; asking
    # for more modes than identities would pad the basis with noise directions.
    if n_modes > len(templates):
        raise ValueError(
            f"n_modes={n_modes} exceeds the {len(templates)} training identities"
        )
    _, singular, right = np.linalg.svd(deviations, full_matrices=False)
    shape_basis = right[:n_modes].T.copy()

    def project(fields: np.ndarray) -> np.ndarray:
        """Latent coordinates of per-vertex fields, one row per field."""

        return fields.reshape(-1, n_vertices * 3) @ shape_basis

    bases = GaugedLatentBases.from_samples(
        project(motions), project(sessions), n_motion=n_motion, n_session=n_session
    )

    from rooted4d.geometry import toy_complex_for_vertices

    # The ring size comes from the data rather than being assumed, so the same
    # builder serves the 24-node fixture and a denser rebuild; a count that no
    # procedural complex has still fails loudly.
    complex_ = toy_complex_for_vertices(n_vertices, **benchmark_topology(root))
    # Per-mode anatomical scale, kept so a prior can shrink each direction by how
    # much the training identities actually vary along it. The singular values
    # were previously computed and discarded, leaving the solver to treat the
    # weakest learned mode as exactly as plausible as the strongest.
    shape_scales = singular[:n_modes] / np.sqrt(max(len(templates) - 1, 1))
    model = SceneModel(
        template_physical=mean_template,
        attachment_map=complex_.attachment_map,
        groups=complex_.groups,
        shape_basis=shape_basis,
        bases=bases,
        n_phase_nodes=n_phase_nodes,
        shape_scales=shape_scales.copy(),
    )
    energy = float(singular[:n_modes].sum() ** 2 / max(float((singular**2).sum()), 1e-30))
    provenance = {
        "training_identities": int(len(templates)),
        "n_modes": int(n_modes),
        "n_motion": int(n_motion),
        "n_session": int(n_session),
        "spectrum_head": [float(v) for v in singular[: min(16, len(singular))]],
        "variance_captured": float((singular[:n_modes] ** 2).sum() / (singular**2).sum()),
        "_energy_unused": energy,
    }
    return model, provenance


def representation_error(model: SceneModel, root: Path | str, split: str) -> dict[str, float]:
    """How far the learned basis is from the donors it never saw.

    This is the floor. An arm whose held-out error sits at this value has
    recovered everything the shape space is capable of expressing, and the
    remaining error is the basis, not the inference.
    """

    templates, _, _ = _identity_geometry(Path(root), split)
    deviations = (templates - model.template_physical).reshape(len(templates), -1)
    coefficients = deviations @ model.shape_basis
    residual = deviations - coefficients @ model.shape_basis.T
    per_vertex = np.linalg.norm(residual.reshape(len(templates), -1, 3), axis=2)
    report = {
        "split": split,
        "identities": int(len(templates)),
        "rms_mm": float(np.sqrt((per_vertex**2).mean())),
        "median_mm": float(np.median(per_vertex)),
        "p95_mm": float(np.percentile(per_vertex, 95)),
        "max_mm": float(per_vertex.max()),
    }
    # The whole-template figure is not the bound on either held-out error, and
    # treating it as one is wrong in both directions: held-out CMR is scored on
    # ``cmr_visible`` and held-out TEE on ``tee_visible``, and the unrepresentable
    # residual is not spread evenly over the template. On this pool the TEE
    # region is roughly half again as hard as the whole template and the CMR
    # region substantially easier, so the whole-template number understates one
    # bound and overstates the other. Each group's own floor is reported.
    for group in ("cmr_visible", "tee_visible"):
        indices = np.sort(model.groups[group])
        report[f"rms_mm_{group}"] = float(
            np.sqrt((per_vertex[:, indices] ** 2).mean())
        )
    return report


def heldout_partition(
    data: dict[str, Any],
    *,
    heldout_cmr_frames: int = 4,
    heldout_tee_fraction: float = 0.25,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """A sample's shared held-out mask: hidden and visible CMR frames, hidden and visible TEE vertices.

    Drawn from the sample's own stored seed, in this order, so every arm and
    every caller that needs the mask (E101 places its anchors on visible
    vertices) gets the same one.
    """

    rng = np.random.default_rng(int(data["seed__sample"]) % (2**63))
    tee_vertices = np.sort(np.asarray(data["tee_indices"]))
    n_frames = len(np.asarray(data["cmr_times"]))
    if heldout_cmr_frames >= n_frames:
        raise ValueError("cannot hold out every CMR frame")
    hidden_frames = np.sort(rng.choice(n_frames, size=heldout_cmr_frames, replace=False))
    visible_frames = np.setdiff1d(np.arange(n_frames), hidden_frames)

    n_hidden_tee = max(1, int(round(heldout_tee_fraction * len(tee_vertices))))
    if n_hidden_tee >= len(tee_vertices):
        raise ValueError("cannot hold out every TEE vertex")
    hidden_tee = np.sort(rng.choice(tee_vertices, size=n_hidden_tee, replace=False))
    visible_tee = np.setdiff1d(tee_vertices, hidden_tee)
    return hidden_frames, visible_frames, hidden_tee, visible_tee


def thin_observations(
    observations: Observations,
    *,
    cmr_keep_every: int = 1,
    tee_keep_every: int = 1,
) -> Observations:
    """Every k-th visible frame of a modality, the held-out partition unchanged (E113).

    CMR keeps every ``cmr_keep_every``-th of its visible frames, counted from
    the first, and TEE every ``tee_keep_every``-th of its frames; TEE anchors
    follow their frames. The hidden CMR frames and the hidden TEE vertices at
    every TEE frame are what the full evidence is scored on, so a thinned
    problem is scored on exactly the same evidence as the full one and only
    what the solver sees shrinks. Both at 1 return the observations unchanged.
    """

    if cmr_keep_every < 1 or tee_keep_every < 1:
        raise ValueError("keep-every factors must be positive")
    cmr = np.arange(len(observations.cmr_times))[::cmr_keep_every]
    tee = np.arange(len(observations.tee_times))[::tee_keep_every]
    anchors = {}
    if observations.tee_anchor_points is not None:
        anchors["tee_anchor_points"] = np.asarray(observations.tee_anchor_points)[tee]
    return replace(
        observations,
        cmr_times=np.asarray(observations.cmr_times)[cmr],
        cmr_points=np.asarray(observations.cmr_points)[cmr],
        tee_times=np.asarray(observations.tee_times)[tee],
        tee_points=np.asarray(observations.tee_points)[tee],
        **anchors,
    )


def benchmark_problem(
    path: Path,
    model: SceneModel,
    config: SolverConfig,
    *,
    heldout_cmr_frames: int = 4,
    heldout_tee_fraction: float = 0.25,
    thinning: dict[str, int] | None = None,
) -> JointProblem:
    """Turn one stored sample into a solvable problem with a shared held-out mask.

    The mask is drawn from the sample's own stored seed, so it is a property of
    the sample rather than of the arm being run: every arm sees exactly the same
    visible evidence and is scored on exactly the same hidden evidence, which is
    what ``shared_evaluation`` in the baseline lock requires. ``thinning`` are
    ``thin_observations``'s factors, applied after the mask is drawn, so the
    held-out evidence of a thinned problem is the full problem's.
    """

    data = _load(path)

    cmr_order = np.argsort(data["cmr_indices"])
    tee_order = np.argsort(data["tee_indices"])
    cmr_vertices = np.asarray(data["cmr_indices"])[cmr_order]
    tee_vertices = np.asarray(data["tee_indices"])[tee_order]
    cmr_points = np.asarray(data["cmr_points"])[:, cmr_order, :]
    tee_points = np.asarray(data["tee_points"])[:, tee_order, :]
    cmr_times = np.asarray(data["cmr_times"])
    tee_times = np.asarray(data["tee_times"])

    hidden_frames, visible_frames, hidden_tee, visible_tee = heldout_partition(
        data, heldout_cmr_frames=heldout_cmr_frames, heldout_tee_fraction=heldout_tee_fraction
    )
    visible_columns = np.searchsorted(tee_vertices, visible_tee)
    hidden_columns = np.searchsorted(tee_vertices, hidden_tee)
    # E101's commissure anchors, where the sample carries them. Only curve
    # evidence reads them (``SolverConfig.curve_evidence``).
    anchors = {}
    if "tee_anchor_vertices" in data:
        anchors = {
            "tee_anchor_vertices": np.asarray(data["tee_anchor_vertices"], dtype=np.int64),
            "tee_anchor_points": np.asarray(data["tee_anchor_points"], dtype=np.float64),
        }

    observations = Observations(
        cmr_times=cmr_times[visible_frames],
        cmr_vertices=cmr_vertices,
        cmr_points=cmr_points[visible_frames],
        tee_times=tee_times,
        tee_vertices=visible_tee,
        tee_points=tee_points[:, visible_columns, :],
        heldout_cmr_times=cmr_times[hidden_frames],
        heldout_cmr_vertices=cmr_vertices,
        heldout_cmr_points=cmr_points[hidden_frames],
        heldout_tee_times=tee_times,
        heldout_tee_vertices=hidden_tee,
        heldout_tee_points=tee_points[:, hidden_columns, :],
        **anchors,
    )
    if thinning:
        observations = thin_observations(observations, **thinning)

    # Pose and phase truth are stored exactly. Identity and motion truth are the
    # best the learned basis can do, because the donor is real geometry that the
    # basis does not span; they are never scored, and exist only so the truth
    # object is complete.
    deviation = (np.asarray(data["template_vertices"]) - model.template_physical).reshape(-1)
    identity = deviation @ model.shape_basis
    motion_fields = np.asarray(data["motion_coefficients"]).reshape(
        len(data["motion_coefficients"]), -1
    )
    motion_latent = (motion_fields @ model.shape_basis) @ model.bases.motion
    rows = 2 * config.fourier_order
    motion = np.zeros((rows, model.bases.n_motion))
    motion[: min(rows, len(motion_latent))] = motion_latent[: min(rows, len(motion_latent))]
    truth = SceneParameters(
        pose_axis_angle=_matrix_to_axis_angle(np.asarray(data["pose_rotation"])),
        pose_translation=np.asarray(data["pose_translation"]),
        phase_offset=float(data["phase_offset"]),
        phase_logits=np.asarray(data["phase_logits"])[: model.n_phase_nodes],
        identity=identity,
        motion=motion,
        session={
            name: np.zeros((session_rows(config), model.bases.n_session))
            for name in model.sessions
        },
    )
    return JointProblem(
        observations=observations,
        truth=truth,
        model=model,
        config=config,
        cmr_noise_mm=float("nan"),
        tee_noise_mm=float("nan"),
    )


def _summary(values: list[float]) -> dict[str, float] | None:
    finite = np.array([v for v in values if v is not None and np.isfinite(v)], dtype=np.float64)
    if finite.size == 0:
        return None
    return {
        "n": int(finite.size),
        "median": float(np.median(finite)),
        "mean": float(finite.mean()),
        "p95": float(np.percentile(finite, 95)),
        "max": float(finite.max()),
    }


def experiment_benchmark_ladder(
    root: Path | str = BENCHMARK_ROOT,
    *,
    split: str = "test",
    n_modes: int = 12,
    n_motion: int = 4,
    n_session: int = 2,
    max_samples: int | None = None,
    max_iterations: int = 40,
    soft_attachment_weight: float = 1e4,
    arms: tuple[str, ...] = BASELINE_IDS,
) -> dict[str, Any]:
    """Experiment E13: the six-arm ladder on real-donor semi-synthetic data."""

    root = Path(root)
    model, provenance = fit_benchmark_model(
        root, n_modes=n_modes, n_motion=n_motion, n_session=n_session
    )
    config = SolverConfig(fourier_order=3, session_order=1, max_iterations=max_iterations)

    floors = {name: representation_error(model, root, name) for name in ("train", split)}

    paths = sample_paths(root, split)
    if max_samples is not None:
        paths = paths[:max_samples]

    rows: list[dict[str, Any]] = []
    for path in paths:
        problem = benchmark_problem(path, model, config)
        for name, result in run_all_arms(
            problem, config, arms=arms, soft_attachment_weight=soft_attachment_weight
        ).items():
            record = result.as_dict()
            record["sample"] = path.stem
            rows.append(record)

    per_arm: dict[str, Any] = {}
    for arm in arms:
        subset = [row for row in rows if row["baseline_id"] == arm]
        per_arm[arm] = {
            "samples": len(subset),
            "failures": sum(1 for row in subset if not row["succeeded"]),
            "heldout_cmr_mm": _summary([row["heldout_cmr_mm"] for row in subset]),
            "heldout_tee_mm": _summary([row["heldout_tee_mm"] for row in subset]),
            "rotation_deg": _summary([row["rotation_deg"] for row in subset]),
            "translation_mm": _summary([row["translation_mm"] for row in subset]),
            "phase_error_cycles": _summary([row["phase_error_cycles"] for row in subset]),
            "attachment_residual_mm": _summary(
                [row["attachment_residual_mm"] for row in subset]
            ),
        }

    return {
        "experiment": "E13_benchmark_ladder_real_donors",
        "claim": (
            "the six locked arms, compared on real-donor geometry the shape space "
            "was never fitted to"
        ),
        "benchmark": str(root),
        "split": split,
        "model_provenance": provenance,
        "representation_floor_mm": floors,
        "per_arm": per_arm,
        "rows": rows,
    }
